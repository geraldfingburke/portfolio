<script>
import { computed } from "vue";
import { useWritingStore } from "@/stores/writing";
import { useGamesStore } from "@/stores/games";
import { useSoftwareStore } from "@/stores/software";

export default {
  name: "AppFooter",
  setup() {
    const writingStore = useWritingStore();
    const gamesStore = useGamesStore();
    const softwareStore = useSoftwareStore();

    const currentYear = new Date().getFullYear();

    // Merge and sort items from all three stores
    const recentStuff = computed(() => {
      const allItems = [];

      // Add games with type and route info
      gamesStore.games.forEach((game) => {
        allItems.push({
          id: game.id,
          title: game.title,
          date: game.releaseDate,
          type: "game",
          route: `/games/${game.id}`,
        });
      });

      // Add software with type and route info
      softwareStore.software.forEach((software) => {
        allItems.push({
          id: software.id,
          title: software.title,
          date: software.startDate,
          type: "software",
          route: `/software/${software.id}`,
        });
      });

      // Add writing with type and route info
      writingStore.writings.forEach((writing) => {
        allItems.push({
          id: writing.id,
          title: writing.title,
          date: writing.publishedAt,
          type: "writing",
          route: `/writing/${writing.slug}`,
        });
      });

      // Sort by date (most recent first) and take top 3
      return allItems
        .sort((a, b) => new Date(b.date) - new Date(a.date))
        .slice(0, 3);
    });

    const formatDate = (dateString) => {
      return new Date(dateString).toLocaleDateString("en-US", {
        year: "numeric",
        month: "short",
        day: "numeric",
      });
    };

    return {
      currentYear,
      recentStuff,
      formatDate,
    };
  },
};
</script>

